function pixelCanvas(spriteDef, scale, frame) {
  if (typeof document === 'undefined') throw new Error('Canvas sprites require a browser');
  const canvas = document.createElement('canvas');
  canvas.width = spriteDef.w * scale; canvas.height = spriteDef.h * scale;
  canvas.style.width = `${spriteDef.w * scale}px`; canvas.style.height = `${spriteDef.h * scale}px`;
  canvas.style.imageRendering = 'pixelated';
  const ctx = canvas.getContext('2d');
  drawSprite(ctx, spriteDef, 0, 0, scale, frame);
  return canvas;
}

export { SPRITES };

export function drawSprite(ctx, name, x, y, scale = 4, frame = 0) {
  const def = typeof name === 'string' ? SPRITES[name] : name;
  if (!def) throw new RangeError(`Unknown sprite: ${name}`);
  const pixels = def.frames[((frame % def.frames.length) + def.frames.length) % def.frames.length];
  for (let row = 0; row < def.h; row += 1) for (let col = 0; col < def.w; col += 1) {
    const color = def.palette[pixels[row]?.[col] || '.'];
    if (color) { ctx.fillStyle = color; ctx.fillRect(Math.round(x + col * scale), Math.round(y + row * scale), scale, scale); }
  }
}

export function spriteDataURL(name, scale = 4, frame = 0) {
  return pixelCanvas(SPRITES[name], scale, frame).toDataURL('image/png');
}

export function spriteEl(name, scale = 4, { animate = false, fps = 6 } = {}) {
  const def = SPRITES[name];
  if (!def) throw new RangeError(`Unknown sprite: ${name}`);
  const canvas = pixelCanvas(def, scale, 0);
  if (animate && def.frames.length > 1 && typeof window !== 'undefined') {
    let frame = 0;
    const timer = window.setInterval(() => {
      if (document.hidden || window.matchMedia?.('(prefers-reduced-motion: reduce)').matches) return;
      frame = (frame + 1) % def.frames.length;
      drawSprite(canvas.getContext('2d'), def, 0, 0, scale, frame);
    }, Math.max(50, 1000 / fps));
    canvas.dataset.animationTimer = String(timer);
    canvas.stopAnimation = () => window.clearInterval(timer);
  }
  return canvas;
}
