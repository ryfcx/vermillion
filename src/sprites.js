function makeHint() {
  const pixels = Array.from({ length: 16 }, () => Array(16).fill('.'));
  const bands = [[5, 10], [3, 12], [2, 13], [1, 14], [1, 14], [2, 13], [3, 12], [4, 11], [5, 10], [6, 9]];
  bands.forEach(([left, right], y) => {
    for (let x = left; x <= right; x += 1) pixels[y + 1][x] = y === 0 || y === bands.length - 1 || x === left || x === right ? 'c' : 'b';
  });
  // Bubble tail on the lower-left edge.
  pixels[11][5] = 'c'; pixels[12][4] = 'c'; pixels[13][3] = 'c';
  pixels[12][5] = 'b'; pixels[13][4] = 'b';
  const question = ['01110', '10001', '00001', '00010', '00100', '00100', '00100'];
  question.forEach((row, y) => [...row].forEach((pixel, x) => { if (pixel === '1') pixels[y + 3][x + 5] = 'w'; }));
  pixels[11][7] = 'w'; pixels[11][8] = 'w';
  return pixels.map(row => row.join(''));
}

