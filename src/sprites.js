function makeGear() {
  return Array.from({ length: 16 }, (_, y) => Array.from({ length: 16 }, (_, x) => {
    const dx = x - 7.5, dy = y - 7.5, radius = Math.hypot(dx, dy);
    const angle = Math.atan2(dy, dx), nearestTooth = Math.round(angle / (Math.PI / 4)) * (Math.PI / 4);
    let delta = Math.abs(angle - nearestTooth) % (Math.PI * 2);
    delta = Math.min(delta, Math.PI * 2 - delta);
    const outer = delta < 0.2 ? 7.4 : 6.3;
    if (radius < 3.1 || radius > outer) return '.';
    return radius < 4.2 && (x + y) % 3 === 0 ? 'w' : 'c';
  }).join(''));
}

