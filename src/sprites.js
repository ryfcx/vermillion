// Five-by-seven pixel alphabet used to make the wordmark from original pixel data.
const GLYPHS = {
  V:['10001','10001','10001','10001','01010','01010','00100'], E:['11111','10000','10000','11110','10000','10000','11111'],
  R:['11110','10001','10001','11110','10100','10010','10001'], M:['10001','11011','10101','10101','10001','10001','10001'],
  I:['11111','00100','00100','00100','00100','00100','11111'], L:['10000','10000','10000','10000','10000','10000','11111'],
  O:['01110','10001','10001','10001','10001','10001','01110'], N:['10001','11001','11001','10101','10011','10011','10001']
};
function wordmark() {
  const word = 'VERMILLION', width = word.length * 6 - 1;
  const canvas = Array.from({ length: 9 }, () => Array(width).fill('.'));
  [...word].forEach((letter, i) => GLYPHS[letter].forEach((line, y) => [...line].forEach((bit, x) => { if (bit === '1') canvas[y + 1][i * 6 + x] = 'p'; })));
  return canvas.map(line => line.join('')).join('\n');
}

